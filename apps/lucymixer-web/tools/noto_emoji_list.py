"""Generates public/editor/notoemoji.js: the catalogue of Google's Noto Animated Emoji for the
editor's sticker picker (codepoints, names and categories only; the GIFs themselves are
fetched from fonts.gstatic.com when a sticker is added).

Source: https://googlefonts.github.io/noto-emoji-animation/ (CC BY 4.0).
Run: python tools/noto_emoji_list.py
"""
import json
import os
import urllib.request

API = "https://googlefonts.github.io/noto-emoji-animation/data/api.json"
OUT = os.path.join(os.path.dirname(__file__), "..", "public", "editor", "notoemoji.js")
ORDER = ["Smileys and emotions", "People", "Animals and nature", "Food and drink", "Travel and places",
         "Activities and events", "Objects", "Symbols", "Flags"]


def main():
    with urllib.request.urlopen(API) as res:
        icons = json.load(res)["icons"]
    groups = {}
    for icon in sorted(icons, key=lambda i: -i.get("popularity", 0)):
        cp = icon["codepoint"]
        if not all(part and all(c in "0123456789abcdef" for c in part) for part in cp.split("_")):
            continue
        name = (icon.get("tags") or [":" + cp + ":"])[0].strip(":").replace(" ", "-")
        cat = (icon.get("categories") or ["Symbols"])[0]
        groups.setdefault(cat, []).append(f"{cp}:{name}")
    cats = [c for c in ORDER if c in groups] + sorted(c for c in groups if c not in ORDER)
    lines = [
        "// Google's Noto Animated Emoji (CC BY 4.0): codepoint:name, by category, most popular first.",
        "// Generated by tools/noto_emoji_list.py from " + API + ".",
        "// The GIF of an entry: https://fonts.gstatic.com/s/e/notoemoji/latest/<codepoint>/512.gif",
        "var IgfvEditor;",
        "IgfvEditor = IgfvEditor || {};",
        "",
        "IgfvEditor.NotoEmoji = {",
        '  credit: "Animated emoji by Google (Noto Emoji), CC BY 4.0",',
        '  url: (cp) => `https://fonts.gstatic.com/s/e/notoemoji/latest/${cp}/512.gif`,',
        "  glyph: (cp) => String.fromCodePoint(...cp.split(\"_\").map((h) => parseInt(h, 16))),",
        "  categories: [",
    ]
    for c in cats:
        lines.append(f"    [{json.dumps(c)}, {json.dumps(' '.join(groups[c]))}],")
    lines += ["  ],", "};", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{sum(len(v) for v in groups.values())} emoji in {len(cats)} categories -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
